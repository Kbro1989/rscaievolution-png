
const fs = require('fs');
const path = require('path');

const CONFIG_DIR = path.resolve(__dirname, '../rsc-cloudflare/rsc-server/rsc-data-local/config');
const OUTPUT_FILE = path.resolve(__dirname, '../rsc-cloudflare/rsc-server/src/constants/ids.js');

function sanitizeName(name) {
    if (!name) return 'UNKNOWN';
    return name
        .toUpperCase()
        .replace(/[^A-Z0-9]+/g, '_') // Replace non-alphanumeric with underscore
        .replace(/^_+|_+$/g, '');     // Trim underscores
}

function generateConstants() {
    console.log('Generating constants from local config...');

    // Load data
    const items = JSON.parse(fs.readFileSync(path.join(CONFIG_DIR, 'items.json'), 'utf8'));
    const npcs = JSON.parse(fs.readFileSync(path.join(CONFIG_DIR, 'npcs.json'), 'utf8'));
    const objects = JSON.parse(fs.readFileSync(path.join(CONFIG_DIR, 'objects.json'), 'utf8'));

    const out = [];
    out.push('// Auto-generated by scripts/generate-constants.cjs');
    out.push('// Do not edit manually if you plan to re-generate.');
    out.push('');

    // Process Items
    out.push('const Items = {');
    const itemMap = new Map();
    items.forEach((item, id) => {
        if (!item.name || item.name === 'null') return;
        let key = sanitizeName(item.name);

        // Handle potential duplicates by appending ID
        if (itemMap.has(key)) {
            key = `${key}_${id}`;
        }
        itemMap.set(key, id);

        out.push(`    ${key}: ${id},`);
    });
    out.push('};');
    out.push('');

    // Process NPCs
    out.push('const Npcs = {');
    const npcMap = new Map();
    npcs.forEach((npc, id) => {
        if (!npc.name || npc.name === 'null') return;
        let key = sanitizeName(npc.name);
        if (npcMap.has(key)) {
            key = `${key}_${id}`;
        }
        npcMap.set(key, id);
        out.push(`    ${key}: ${id},`);
    });
    out.push('};');
    out.push('');

    // Process Objects
    out.push('const Objects = {');
    const objMap = new Map();
    objects.forEach((obj, id) => {
        if (!obj.name || obj.name === 'null') return;
        let key = sanitizeName(obj.name);
        if (objMap.has(key)) {
            key = `${key}_${id}`;
        }
        objMap.set(key, id);
        out.push(`    ${key}: ${id},`);
    });
    out.push('};');
    out.push('');

    out.push('module.exports = { Items, Npcs, Objects };');

    // Ensure directory exists
    const outDir = path.dirname(OUTPUT_FILE);
    if (!fs.existsSync(outDir)) {
        fs.mkdirSync(outDir, { recursive: true });
    }

    fs.writeFileSync(OUTPUT_FILE, out.join('\n'));
    console.log(`Constants written to ${OUTPUT_FILE}`);
    console.log(`Stats: Items(${itemMap.size}), Npcs(${npcMap.size}), Objects(${objMap.size})`);
}

generateConstants();
